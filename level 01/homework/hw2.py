#strings: are used to store text data. A string is represented using the str class and can be created using single, double or triple quote. example: name="Teodore"

#integers: value is represented by int class. it contains positive or negative whole numbers (without fractions or decimals). example: age=15

#float: value is represented by float class. it is a real number with a floating-point representation. it is specified by a decimal point. price=5.99
