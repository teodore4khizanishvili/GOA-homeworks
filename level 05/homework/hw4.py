number1 = int(input("Please enter one number: "))
number2 = int(input("Please enter another number: "))
number3 = int(input("Please enter one more number: "))

print(number1 < number2 < number3)
print(number1 <= number2 <= number3)
print(number1 > number2 > number3)
print(number1 >= number2 >= number3)
print(number1 != number2 != number3)
print(number1 == number2 == number3)
